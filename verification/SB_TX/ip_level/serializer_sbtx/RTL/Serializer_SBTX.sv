
/*---------Description------------------//

this Module serializes Messages by means of control signals 
generated by the SB_TX FSM.

//---------------------------------------*/


module Serializer_64_SBTX #(parameter DATA_WIDTH=64)
(
    input  logic clk                     ,          // Clock input
    input  logic rst_n                   ,          // Active-low reset
    input  logic load                    ,          // signal to load the data to be serialized on the SB lane
    input  logic Enable                  ,          // Enable signal to Serialize the Data_in
    input  logic [DATA_WIDTH-1:0] data_in,          // 64-bit parallel input from the FIFO
    output logic data_out                ,          // Serialized 1-bit output
    output logic start_64                           // signal to start the 64 cycles timer
);

logic [DATA_WIDTH-1:0] shift_reg;                   // Shift register      

always_ff @(posedge clk or negedge rst_n) begin

    if (!rst_n) begin

        shift_reg <='b0;
        start_64  <='b0;

    end else if (load) begin

        shift_reg <= data_in;        // Load parallel data
        start_64  <= 1'b1; 
        
    end else if (Enable) begin

        shift_reg <= shift_reg >> 1; // Shift right
        start_64  <= 1'b0;

    end else begin 
        
        shift_reg <= 'b0; 

    end 

end

assign data_out = shift_reg[0]; // Output LSB first


endmodule

